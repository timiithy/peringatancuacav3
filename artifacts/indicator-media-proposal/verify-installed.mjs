import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const dir=path.dirname(fileURLToPath(import.meta.url));
const require=createRequire(path.resolve(dir,'../../frontend/package.json'));
const {chromium,expect}=require('@playwright/test');
const browser=await chromium.launch({channel:'chrome',headless:true});
try {
 const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce',serviceWorkers:'block'});
 const page=await context.newPage();
 const requests=[];
 page.on('request',r=>{if(new URL(r.url()).pathname.startsWith('/indicators/'))requests.push(r.url());});
 await page.goto('http://localhost:3001/lapor');
 assert.equal(requests.length,0,'Collapsed categories must not download artwork');
 await page.getByRole('button',{name:/^Bintang dan Bulan/}).click();
 const star=page.locator('label[for="indicator-Wn-16"]');
 await star.scrollIntoViewIfNeeded();
 await expect(star.locator('img')).toHaveJSProperty('complete',true);
 await expect.poll(()=>star.locator('img').evaluate(i=>i.naturalWidth)).toBeGreaterThan(0);
 await star.screenshot({path:path.join(dir,'wn-16-in-report.png')});
 await star.locator('.aspect-video').screenshot({path:path.join(dir,'wn-16-illustration.png')});
 assert.ok(requests.every(url=>/wn-(12|13|14|16)\./.test(url)),'Other categories must not download artwork');
 await page.getByText('Sumber gambar',{exact:true}).click();
 await expect(page.locator('details')).toHaveAttribute('open','');
 await expect(page.locator('details a')).toHaveCount(18);
 await expect(page.getByRole('checkbox',{checked:true})).toHaveCount(0);
 await page.route('**/indicators/wn-1.svg',route=>route.abort());
 await page.getByRole('button',{name:/^Awan dan Hujan/}).click();
 const first=page.locator('label[for="indicator-Wn-1"]');
 await first.scrollIntoViewIfNeeded();
 await expect(first.getByText('Ilustrasi Wn-1',{exact:true})).toBeVisible();
 await first.click();
 await expect(page.getByRole('checkbox',{name:/^Wn-1 /})).toBeChecked();
 const svg=await context.newPage();
 await svg.goto('http://localhost:3001/indicators/wn-2.svg');
 assert.equal(await svg.evaluate(()=>document.getAnimations().length),0,'Reduced motion must disable SVG animation');
 await svg.emulateMedia({reducedMotion:'no-preference'});
 await svg.reload();
 assert.ok(await svg.evaluate(()=>document.getAnimations().length)>0,'Normal mode must retain the approved animation');
 console.log('PASS: category-scoped requests, star illustration, credits, broken-image selection, and reduced-motion behavior.');
}finally{await browser.close();}
